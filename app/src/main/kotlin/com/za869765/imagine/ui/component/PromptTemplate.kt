                                    }
                                }
                            }
                            if (rowCats.size == 1) Box(modifier = Modifier.weight(1f))
                        }
                    }
                } else {
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clip(RoundedCornerShape(10.dp))
                            .clickable { expandedField = null; openCategory = null }
                            .padding(vertical = 8.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
